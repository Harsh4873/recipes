import type { Nutrition } from '../model';

export interface IngredientRecord {
  readonly id: string;
  readonly name: string;
  readonly referenceGrams: number;
  readonly nutrition: Nutrition;
  readonly estimated: boolean;
  readonly sourceLabel: string;
  readonly sourceUrl?: string;
  readonly sourceNote: string;
  /** Retailer buy link from curated handoff data. Keep this separate from nutrition sourceUrl. */
  readonly walmartUrl?: string;
}

const USDA = 'https://fdc.nal.usda.gov/';

function nutrition(value: Nutrition): Nutrition {
  return Object.freeze({ ...value });
}

function ingredient(input: IngredientRecord): IngredientRecord {
  return Object.freeze({
    ...input,
    nutrition: nutrition(input.nutrition),
  });
}

